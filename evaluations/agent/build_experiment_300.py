def build_cases() -> list[dict]:
    cases = []
    for category, title, level, routes, profile, behavior, body in GROUPS:
        rows = [line.strip() for line in body.strip().splitlines() if line.strip()]
        if len(rows) != 30:
            raise ValueError(f"{category}: expected 30 cases, got {len(rows)}")
        for index, row in enumerate(rows, 1):
            query, check = row.split("|", 1)
            cases.append(
                {
                    "schema_version": "sales-acceptance-v1",
                    "case_id": f"exp-{category}-{index:02d}",
                    "category": category,
                    "category_label": title,
                    "level": level,
                    "query": query,
                    "candidate_routes": routes,
                    "expected_behavior": behavior,
                    "acceptance_checks": [
                        check,
                        "不得暴露未授权数据；事实和数值必须有可验证来源。",
                    ],
                    "fixture_profile": profile,
                    "setup": PROFILES[profile],
                    "principal_profile": "bind_per_case_least_privilege",
                    "reference_time": "2026-09-23T12:00:00+08:00",
                    "timezone": "Asia/Shanghai",
                    "reference_answer": None,
                    "reference_evidence": [],
                    "readiness": "requires_fixture_and_oracle_review",
                    "execution_mode": "acceptance_spec_not_mock_runner_input",
                    "split": "holdout_candidate" if index % 5 == 0 else "development",
                    "result": None,
                }
            )
    validate_cases(cases)
    return cases


def validate_cases(cases: list[dict]) -> None:
    assert len(cases) == 300
    assert len({case["case_id"] for case in cases}) == 300
    assert len({case["query"] for case in cases}) == 300
    assert set(Counter(case["category"] for case in cases).values()) == {30}
    assert Counter(case["split"] for case in cases) == {
        "development": 240,
        "holdout_candidate": 60,
    }
    for case in cases:
        assert case["query"] and len(case["acceptance_checks"]) >= 2
        assert case["reference_answer"] is None and case["result"] is None


